export const dateText = (v) =>
  v ? String(v).replace("T", " ").slice(0, 16) : "—";
export const optionLabel = (row, source) =>
  source === "lessons"
    ? `${row.title || "课次"} · ${dateText(row.startTime)}`
    : row.name ||
      row.title ||
      row.displayName ||
      row.username ||
      `记录 ${row.id}`;
